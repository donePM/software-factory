import { expect, test } from 'claude-code/testing'
import { renderTexts } from '../lib/texts.ts'
import { fakeCtx } from './support/host.ts'

const P = '/p'

test('renderTexts exports the agent, skill, and pipeline files in path order', async () => {
  const ctx = fakeCtx({
    files: {
      [`${P}/agents/b.md`]: 'B "quoted"\n',
      [`${P}/agents/a.md`]: 'A\n`tick` ${x}',
      [`${P}/agents/notes.txt`]: 'not a text file',
      [`${P}/skills/run/SKILL.md`]: 'run',
      [`${P}/skills/run/other.md`]: 'not the skill file',
      [`${P}/pipeline.md`]: 'loop',
      [`${P}/README.md`]: 'not read',
    },
  })
  const text = await renderTexts(ctx.fs, P)
  expect(text.split('\n')[0]).toBe('// Generated by scripts/texts.ts from the agent, skill, and pipeline files. Do not edit.')
  expect(text).toContain('export const TEXTS = {\n')
  const keys = [...text.matchAll(/^ {2}("[^"]+"): /gm)].map(m => JSON.parse(m[1]!) as string)
  expect(keys).toEqual(['agents/a.md', 'agents/b.md', 'pipeline.md', 'skills/run/SKILL.md'])
  expect(text).toContain(`  "agents/a.md": ${JSON.stringify('A\n`tick` ${x}')},\n`)
  expect(text).toContain(`  "agents/b.md": ${JSON.stringify('B "quoted"\n')},\n`)
  expect(text.endsWith('}\n')).toBe(true)
})

test('renderTexts gives an empty module for a plugin without text files', async () => {
  const text = await renderTexts(fakeCtx({ files: {} }).fs, P)
  expect(text.endsWith('export const TEXTS = {\n}\n')).toBe(true)
})
