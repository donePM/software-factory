import type { Fs } from './types.ts'

// The generated module with the text files of a plugin. Plugin tests have no fs, so they import it.
export const TEXTS_MODULE = 'tests/generated/texts.ts'
export const TEXTS_SCRIPT = 'scripts/texts.ts'

type ReadDir = Pick<Fs, 'read' | 'list'>

async function names(fs: ReadDir, dir: string): Promise<string[]> {
  try {
    return await fs.list(dir)
  } catch {
    return []
  }
}

// The agents, the skill files, and the pipeline, as paths relative to the plugin.
async function sources(fs: ReadDir, dir: string): Promise<string[]> {
  const out = (await names(fs, `${dir}/agents`)).filter(n => n.endsWith('.md')).map(n => `agents/${n}`)
  for (const s of await names(fs, `${dir}/skills`)) {
    if ((await names(fs, `${dir}/skills/${s}`)).includes('SKILL.md')) out.push(`skills/${s}/SKILL.md`)
  }
  if ((await names(fs, dir)).includes('pipeline.md')) out.push('pipeline.md')
  return out.sort()
}

export async function renderTexts(fs: ReadDir, dir: string): Promise<string> {
  const lines = [`// Generated by ${TEXTS_SCRIPT} from the agent, skill, and pipeline files. Do not edit.`, 'export const TEXTS = {']
  for (const p of await sources(fs, dir)) lines.push(`  ${JSON.stringify(p)}: ${JSON.stringify(await fs.read(`${dir}/${p}`))},`)
  lines.push('}', '')
  return lines.join('\n')
}
